export function pickUIT2(hint: string | null | undefined): UIT2 {
  if (!hint) return UI2_EN;
  const tag = hint.toLowerCase();
  const tryKeys = [tag, tag.replace(/-/g, ''), tag.split('-')[0]];
  for (const k of tryKeys) {
    const o = UI2_LANG[k];
    if (o) return { ...UI2_EN, ...o };
  }
  return UI2_EN;
}

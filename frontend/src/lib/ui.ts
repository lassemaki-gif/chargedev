export function pickUIT(hint: string | null | undefined): UIT {
  if (!hint) return UI_LANG.en;
  const tag = hint.toLowerCase();
  if (tag in UI_LANG) return UI_LANG[tag];
  const compact = tag.replace(/-/g, '');
  if (compact in UI_LANG) return UI_LANG[compact];
  const base = tag.split('-')[0];
  if (base in UI_LANG) return UI_LANG[base];
  return UI_LANG.en;
}



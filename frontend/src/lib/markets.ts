export function pickSellT(hint: string | null | undefined): SellT {
  if (!hint) return SELL_LANG.en;
  const tag = hint.toLowerCase();
  // Exact match (e.g. "fi").
  if (tag in SELL_LANG) return SELL_LANG[tag];
  // Compact form without hyphen (e.g. "pt-BR" → "ptbr").
  const compact = tag.replace(/-/g, '');
  if (compact in SELL_LANG) return SELL_LANG[compact];
  // Base language (e.g. "fi-FI" → "fi", "nb-NO" → "nb").
  const base = tag.split('-')[0];
  if (base in SELL_LANG) return SELL_LANG[base];
  return SELL_LANG.en;
}
